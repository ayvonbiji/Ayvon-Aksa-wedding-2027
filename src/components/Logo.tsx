import { asset } from '../lib/assets';
import { wedding } from '../config/wedding';

type Variant = 'monogram' | 'compact' | 'wordmark' | 'lockup' | 'mono';

const files: Record<Variant, string> = {
  monogram: 'brand/monogram.svg',
  compact: 'brand/logo-header.svg',
  wordmark: 'brand/wordmark.svg',
  lockup: 'brand/logo-invitation.svg',
  mono: 'brand/monogram-mono.svg',
};

interface Props {
  variant?: Variant;
  className?: string;
  /** Decorative logos (next to visible names) should be hidden from screen readers. */
  decorative?: boolean;
  width?: number;
  height?: number;
}

/** Reusable wedding logo. Files are generated by `npm run assets`. */
export function Logo({ variant = 'monogram', className, decorative = false, width, height }: Props) {
  const label = `${wedding.groom.first} & ${wedding.bride.first} wedding ${variant === 'wordmark' ? 'wordmark' : 'monogram'}`;
  return (
    <img
      src={asset(files[variant])}
      alt={decorative ? '' : label}
      aria-hidden={decorative || undefined}
      className={className}
      width={width}
      height={height}
      decoding="async"
      draggable={false}
    />
  );
}
